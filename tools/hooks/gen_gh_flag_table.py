#!/usr/bin/env python3
"""Generate `gh_flag_table.json` from the installed gh's own grammar
(harmonic-forge#1447 reforge).

The close and merge gate parses `gh api`, `gh issue ...` and `gh pr ...` argv
with `gh_argv`, a pflag-faithful tokenizer. Its flag table is this file's
output: every flag (long name, shorthand, value-taking or boolean) of every
command path under `api`, `issue` and `pr`, read from `gh <path> --help`, plus
the root's builtin command list (read from `gh --help`, extensions excluded).
The table is pinned to the gh version it was read from;
`test_gh_argv.FlagTableFreshness` regenerates it in memory and fails when the
installed gh is the pinned version and the two differ.

Usage:
  python3 tools/hooks/gen_gh_flag_table.py            # rewrite the table and the shim block
  python3 tools/hooks/gen_gh_flag_table.py --check    # exit 1 when either is stale
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE / "gh_flag_table.json"
SHIM = HERE.parent / "gh" / "gh_shim"
GATED_ROOTS = ("api", "issue", "pr")
#: cobra's hidden completion commands: they print candidates, never run a command.
HIDDEN_BUILTINS = ("__complete", "__completeNoDesc")
#: Root spellings that are not listed as commands but never run one.
ROOT_EXTRAS = ("help", "version", "--help", "-h", "--version")

_FLAG_LINE = re.compile(
    r"^\s+(?:-(?P<short>[A-Za-z0-9]), )?--(?P<long>[A-Za-z0-9][\w-]*)(?: (?P<type>\S+))?(?:\s{2,}|$)")
_COMMAND_LINE = re.compile(r"^  (?P<name>[\w-]+):\s")
_SECTION = re.compile(r"^[A-Z][A-Z ]+$")

BLOCK_BEGIN = "# BEGIN generated by tools/hooks/gen_gh_flag_table.py -- do not edit by hand"
BLOCK_END = "# END generated"


def real_gh() -> str:
    """The real gh binary: the first `gh` on PATH that is not a gh shim
    (this checkout's or any other's)."""
    for directory in os.environ.get("PATH", "").split(os.pathsep):
        candidate = os.path.join(directory, "gh")
        if os.path.isfile(candidate) and os.path.basename(os.path.realpath(candidate)) != "gh_shim":
            return candidate
    return "/usr/bin/gh"


def _help(gh: str, path: list[str]) -> str:
    done = subprocess.run([gh, *path, "--help"], capture_output=True, text=True, timeout=30,
                          env={**os.environ, "NO_COLOR": "1", "GH_PAGER": "cat"})
    if done.returncode:
        raise RuntimeError(f"`gh {' '.join(path)} --help` exited {done.returncode}: {done.stderr}")
    return done.stdout


def gh_version(gh: str) -> str:
    done = subprocess.run([gh, "--version"], capture_output=True, text=True, timeout=30)
    match = re.search(r"gh version (\S+)", done.stdout)
    if not match:
        raise RuntimeError(f"unreadable `gh --version`: {done.stdout!r}")
    return match.group(1)


def _sections(text: str) -> dict[str, list[str]]:
    sections: dict[str, list[str]] = {}
    current = ""
    for line in text.splitlines():
        if _SECTION.match(line):
            current = line.strip()
            sections.setdefault(current, [])
        elif current:
            sections[current].append(line)
    return sections


def _flags(lines: list[str]) -> dict[str, dict]:
    flags: dict[str, dict] = {}
    for line in lines:
        match = _FLAG_LINE.match(line)
        if match:
            flags["--" + match.group("long")] = {"short": match.group("short"),
                                                  "value": match.group("type") is not None}
    return flags


def _commands(sections: dict[str, list[str]], skip: tuple[str, ...] = ()) -> list[str]:
    names: list[str] = []
    for title, lines in sections.items():
        if not title.endswith("COMMANDS") or title in skip:
            continue
        names.extend(m.group("name") for m in map(_COMMAND_LINE.match, lines) if m)
    return names


def _aliases(sections: dict[str, list[str]]) -> list[str]:
    """`ALIASES` lines read `gh pr ls` / `gh issue new`; the last word is the alias."""
    return [line.split()[-1] for line in sections.get("ALIASES", []) if line.strip().startswith("gh ")]


def build(gh: str) -> dict:
    root = _sections(_help(gh, []))
    builtins = sorted({*_commands(root, skip=("EXTENSION COMMANDS",)), *HIDDEN_BUILTINS, *ROOT_EXTRAS})
    commands: dict[str, dict] = {}

    def walk(path: list[str]) -> None:
        sections = _sections(_help(gh, path))
        flags = {**_flags(sections.get("INHERITED FLAGS", [])), **_flags(sections.get("FLAGS", []))}
        flags.setdefault("--help", {"short": "h", "value": False})
        flags["--help"]["short"] = "h"  # cobra adds -h to every command's --help
        children = _commands(sections)
        commands[" ".join(path)] = {"flags": dict(sorted(flags.items())), "aliases": sorted(_aliases(sections)),
                                    "children": sorted(children)}
        for child in children:
            walk([*path, child])

    for root_name in GATED_ROOTS:
        walk([root_name])
    return {"gh_version": gh_version(gh), "builtins": builtins, "commands": commands}


def shim_block(table: dict) -> str:
    names = ", ".join(json.dumps(name) for name in table["builtins"])
    return (f"{BLOCK_BEGIN} (gh {table['gh_version']})\n"
            f"_GH_BUILTINS = frozenset({{{names}}})\n{BLOCK_END}")


def render_shim(text: str, table: dict) -> str:
    pattern = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), re.S)
    if not pattern.search(text):
        raise RuntimeError("gh_shim has no generated builtins block")
    return pattern.sub(lambda _m: shim_block(table), text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table = build(real_gh())
    rendered = json.dumps(table, indent=1, sort_keys=True) + "\n"
    shim_text = SHIM.read_text()
    new_shim = render_shim(shim_text, table)
    if args.check:
        stale = (not TABLE.exists() or TABLE.read_text() != rendered) or new_shim != shim_text
        if stale:
            sys.stderr.write("gh_flag_table.json or the gh_shim builtins block is stale; regenerate\n")
        return 1 if stale else 0
    TABLE.write_text(rendered)
    SHIM.write_text(new_shim)
    return 0


if __name__ == "__main__":
    sys.exit(main())
